// Overview thumbnails: freezes every stop at its `at` and writes public/talk/overview/<stopId>.webp
// and lists them in src/talk/overview/thumbs.ts so the overview never requests a missing file.
// Options: --base http://localhost:3102 (or STILLS_BASE_URL) --only id,id --out public/talk/overview
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";

import { openStagePage } from "./stage-page.ts";
import { DEFAULT_BASE_URL, stillUrl } from "./stills-args.ts";

const THUMB = { width: 480, height: 270, quality: 0.86 };

const flags = new Map<string, string>();
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const [key = "", ...rest] = String(argv[i]).replace(/^--/, "").split("=", 2);
  flags.set(key, rest.length > 0 ? rest.join("=") : String(argv[++i] ?? ""));
}
const baseUrl = (flags.get("base") ?? process.env["STILLS_BASE_URL"] ?? DEFAULT_BASE_URL).replace(
  /\/$/,
  "",
);
const DEFAULT_OUT = resolve("public/talk/overview");
const out = resolve(flags.get("out") ?? DEFAULT_OUT);
const only = flags.get("only")?.split(",").filter(Boolean);
mkdirSync(out, { recursive: true });

const { browser, page } = await openStagePage();

// The dev server serves source modules, so the stop list comes from the app itself.
type StopAt = { id: string; at: number };
async function readStops(): Promise<StopAt[]> {
  await page.goto(`${baseUrl}/`, { waitUntil: "load" });
  await page.waitForSelector("[data-stage]", { timeout: 60_000 });
  return page.evaluate(async () => {
    const scene = "/src/talk/talk-scene.tsx";
    const mod = (await import(/* @vite-ignore */ scene)) as { TALK_STOPS: readonly StopAt[] };
    return mod.TALK_STOPS.map(({ id, at }) => ({ id, at }));
  });
}
// A cold dev server may reload the page once while it optimizes deps.
const stops = await readStops().catch(readStops);

const encoder = await browser.newPage();
const toWebp = (png: Buffer) =>
  encoder.evaluate(
    async ({ b64, width, height, quality }) => {
      const img = new Image();
      img.src = `data:image/png;base64,${b64}`;
      await img.decode();
      const canvas = document.createElement("canvas");
      canvas.width = width;
      canvas.height = height;
      const ctx = canvas.getContext("2d");
      if (!ctx) throw new Error("2D canvas unavailable");
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(img, 0, 0, width, height);
      return canvas.toDataURL("image/webp", quality).split(",")[1] ?? "";
    },
    { b64: png.toString("base64"), ...THUMB },
  );

for (const stop of stops) {
  if (only && !only.includes(stop.id)) continue;
  await page.goto(stillUrl({ baseUrl, path: "/", w: 1 }, stop.at), { waitUntil: "load" });
  await page.waitForFunction(() => window.__stageReady === true, undefined, { timeout: 60_000 });
  const file = join(out, `${stop.id}.webp`);
  writeFileSync(file, Buffer.from(await toWebp(await page.screenshot()), "base64"));
  console.log(`${stop.id} τ=${stop.at} → ${file}`);
}

await browser.close();

if (out === DEFAULT_OUT) {
  const ids = readdirSync(out)
    .filter((name) => name.endsWith(".webp"))
    .map((name) => name.slice(0, -".webp".length))
    .sort();
  const manifest = resolve("src/talk/overview/thumbs.ts");
  writeFileSync(
    manifest,
    `// Generated by \`pnpm overview:thumbs\`: stops with a thumbnail in public/talk/overview.\nexport const THUMBS: ReadonlySet<string> = new Set([\n${ids.map((id) => `  ${JSON.stringify(id)},\n`).join("")}]);\n`,
  );
  console.log(`${ids.length} thumbnails → ${manifest}`);
}
