// Fetches a favicon for every link host in the speaker notes: `pnpm favicons`
// Writes public/talk/favicons/<host>.png (existing files are kept) and src/talk/favicon-hosts.ts.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outDir = join(root, "public/talk/favicons");
const modulePath = join(root, "src/talk/favicon-hosts.ts");

const notes = readFileSync(join(root, "src/talk/notes.md"), "utf8");
const LINKS = [/\]\((https?:\/\/[^)\s]+)\)/g, /<mention-page url="([^"]+)"/g];
const urls = LINKS.flatMap((pattern) => [...notes.matchAll(pattern)].map((match) => match[1]));
const hosts = [...new Set(urls.map((url) => new URL(url).host))].sort();

mkdirSync(outDir, { recursive: true });
const fetched = hosts.filter((host) => {
  const file = join(outDir, `${host}.png`);
  if (existsSync(file)) return true;
  try {
    const source = `https://www.google.com/s2/favicons?domain=${host}&sz=64`;
    execFileSync("curl", ["-fsSL", "-o", file, source]);
    console.log(`${host} → ${file}`);
    return true;
  } catch {
    console.warn(`${host}: no favicon`);
    return false;
  }
});

const list = fetched.map((host) => `  "${host}",`).join("\n");
writeFileSync(
  modulePath,
  `// Generated by scripts/fetch-favicons.ts: hosts with a favicon in public/talk/favicons.\nexport const FAVICON_HOSTS: ReadonlySet<string> = new Set([\n${list}\n]);\n`,
);
console.log(`${fetched.length}/${hosts.length} hosts → ${modulePath}`);
